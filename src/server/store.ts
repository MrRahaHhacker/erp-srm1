function daysFromNow(days: number): string {
  return new Date(Date.now() + days * 24 * 60 * 60 * 1000).toISOString();
}

function hoursAgo(hours: number): string {
  return new Date(Date.now() - hours * 60 * 60 * 1000).toISOString();
}

export function calculateQuotationLine(
  item: Omit<QuotationLineItem, 'netUnitPrice' | 'gstAmount' | 'totalLandedCost'>,
  quantity: number,
): QuotationLineItem {
  const discountFactor = Math.max(0, 1 - (item.discountPercent || 0) / 100);
  const netUnitPrice = Number((item.basicUnitPrice * discountFactor).toFixed(2));
  const basicSubtotal = netUnitPrice * quantity;
  const gstAmount = Number(((basicSubtotal * (item.gstPercent || 0)) / 100).toFixed(2));
  const totalLandedCost = Number(
    (
      basicSubtotal +
      gstAmount +
      (item.freight || 0) +
      (item.packingForwarding || 0) +
      (item.toolingCost || 0) +
      (item.insurance || 0) +
      (item.otherCharges || 0)
    ).toFixed(2),
  );
  return {
    ...item,
    netUnitPrice,
    gstAmount,
    totalLandedCost,
  };
}

