export function getDb(): SrmDatabase {
  if (dbCache) return dbCache;
  try {
    const loaded = loadDatabaseFromSqlite();
    if (loaded) {
      dbCache = loaded;
      return dbCache;
    }
  } catch {
    // Fallback to clean seed if SQLite read fails
  }
  dbCache = createSeedDatabase();
  saveDb();
  return dbCache;
}

export function saveDb(): void {
  if (!dbCache) return;
  try {
    persistDatabaseToSqlite(dbCache);
  } catch (err) {
    console.error('SQLite persistence error:', err);
  }
}

export function nextNumber(
  objectType: SrmDatabase['numberRanges'][number]['objectType'],
): string {
  const db = getDb();
  const range = db.numberRanges.find((r) => r.objectType === objectType);
  if (!range) return `${objectType}-${Date.now()}`;
  const num = range.currentNumber;
  range.currentNumber += 1;
  return `${range.prefix}${String(num).padStart(range.padding, '0')}`;
}

export function recordAudit(entry: Omit<AuditLog, 'id' | 'timestamp'>): void {
  const db = getDb();
  db.auditLogs.unshift({
    ...entry,
    id: `AUD-${Date.now()}-${Math.floor(Math.random() * 1000)}`,
    timestamp: new Date().toISOString(),
  });
  if (db.auditLogs.length > 500) {
    db.auditLogs.length = 500;
  }
}
